#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off
/**
 * Grows her motion library (M-081): a seen or seed performance that passed every check and scored 4 or more, and,
 * with `--physics <verdicts.json>` (the offline MuJoCo check, `{id: {pass}}`), passed that too. Unseen never enter.
 * usage: node harvest.ts [--physics <verdicts.json>] <results.json>... > a file, then copy over bodyMotionLibrary.ts
 */
import * as NodeFS from "node:fs";

import { decodeBodyMove } from "../../packages/tessaya-shared/src/bodyControl.ts";
import type { MotionEntry } from "../../packages/tessaya-shared/src/bodyLibrary.ts";

interface Row {
  readonly id: string;
  readonly said: string;
  readonly split: string;
  readonly score: number;
  readonly pass: boolean;
  readonly calls: string;
  readonly bodyInputs?: ReadonlyArray<unknown>;
  readonly graded: { readonly corrections: number; readonly overSpeed: ReadonlyArray<string> };
}

const args = process.argv.slice(2);
const at = args.indexOf("--physics");
const physics =
  at < 0
    ? null
    : (JSON.parse(NodeFS.readFileSync(args.splice(at, 2)[1]!, "utf8")) as Record<
        string,
        { readonly pass: boolean }
      >);
const best = new Map<string, MotionEntry>();
for (const file of args) {
  for (const r of JSON.parse(NodeFS.readFileSync(file, "utf8")) as Row[]) {
    if (r.split !== "seen" || !r.pass || r.graded.corrections > 0 || r.graded.overSpeed.length > 0)
      continue;
    if (!/tessaya_body_move/.test(r.calls) || /tessaya_body_scene/.test(r.calls)) continue;
    // the last move that decodes is what played; one already resolved through the library is not new
    const move = [...(r.bodyInputs ?? [])]
      .toReversed()
      .find((m) => decodeBodyMove(m).ok && !(typeof m === "object" && m !== null && "intent" in m));
    if (move === undefined) continue;
    if (physics !== null && physics[r.id]?.pass !== true) continue;
    const was = best.get(r.said);
    if (was !== undefined && was.score >= r.score) continue;
    best.set(r.said, {
      id: r.id,
      text: r.said,
      move: move as Record<string, unknown>,
      score: r.score,
      source: file.split("/").slice(-2, -1)[0] ?? "run",
    });
  }
}
const entries = [...best.values()].toSorted((a, b) => a.id.localeCompare(b.id));
process.stdout.write(
  `// Generated by evals/tessaya-body-direction/harvest.ts from validated performances; regenerate, don't hand-edit.\n` +
    `import type { MotionEntry } from "./bodyLibrary.ts";\n\n` +
    `export const MOTION_LIBRARY: ReadonlyArray<MotionEntry> = ${JSON.stringify(entries, null, 2)};\n`,
);
console.error(`${entries.length} entries`);
