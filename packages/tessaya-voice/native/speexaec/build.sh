#!/usr/bin/env bash
# Builds speexdsp 1.2.1's echo canceller (mdf.c) and preprocessor (its residual echo suppression) to wasm, then writes
# src/room/speexAecWasm.ts. Needs Python 3 for zig (pip ziglang), which brings its own wasi libc. speexdsp is BSD-licensed.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -sL https://github.com/xiph/speexdsp/archive/refs/tags/SpeexDSP-1.2.1.tar.gz -o "$work/s.tgz"
echo "SHA  $work/s.tgz" | sed "s/SHA/$(cat "$here/speexdsp.sha256")/" | sha256sum -c - >/dev/null
tar xzf "$work/s.tgz" -C "$work"
d="$work/speexdsp-SpeexDSP-1.2.1"
mkdir -p "$work/inc/speex"
cp "$d"/include/speex/*.h "$work/inc/speex/"
printf '#include <stdint.h>\ntypedef int16_t spx_int16_t;\ntypedef uint16_t spx_uint16_t;\ntypedef int32_t spx_int32_t;\ntypedef uint32_t spx_uint32_t;\n' >"$work/inc/speex/speexdsp_config_types.h"
python3 -m venv "$work/venv" && "$work/venv/bin/pip" -q install ziglang==0.13.0.post1
"$work/venv/bin/python" -m ziglang cc -target wasm32-wasi -O2 -mexec-model=reactor -DHAVE_CONFIG_H -I"$here" -I"$work/inc" \
  "$here/shim.c" "$d"/libspeexdsp/{mdf,preprocess,fftwrap,smallft,filterbank}.c -o "$work/aec.wasm" -Wl,--strip-all \
  -Wl,--export=aec_create,--export=aec_buf,--export=aec_process,--export=aec_reset,--export=aec_free
{
  echo "// Generated by native/speexaec/build.sh from speexdsp 1.2.1 (BSD licence, Xiph.Org). Do not edit."
  echo "export const SPEEX_AEC_WASM ="
  echo "  \"$(base64 -w0 "$work/aec.wasm")\";"
} >"$here/../../src/room/speexAecWasm.ts"
