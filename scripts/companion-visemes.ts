// @effect-diagnostics nodeBuiltinImport:off
/**
 * Her mouth shapes for the Character Studio's page scripts: `TCS.g2v` in apps/web/public/companion/speech.js is built
 * from `wordUnits` in packages/tessaya-shared/src/visemes.ts, the one table the desktop's voice also uses, and written
 * between the markers there. `node scripts/companion-visemes.ts` rewrites it; companion-visemes.test.ts fails while it
 * is stale.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { build } from "esbuild";

const root = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
export const SPEECH_JS = NodePath.join(root, "apps/web/public/companion/speech.js");
const SOURCE = NodePath.join(root, "packages/tessaya-shared/src/visemes.ts");
const BEGIN =
  " // BEGIN generated by scripts/companion-visemes.ts from tessaya-shared visemes.ts: do not edit";
const END = " // END generated";

/** The generated block: `wordUnits` bundled as it ships, behind `TCS.g2v`. */
export const visemesBlock = async (): Promise<string> => {
  const out = await build({
    stdin: {
      contents: `export { wordUnits } from ${JSON.stringify(SOURCE)};`,
      resolveDir: root,
      loader: "ts",
    },
    bundle: true,
    format: "iife",
    globalName: "VISEMES",
    target: "es2020",
    write: false,
    legalComments: "none",
    // Its path comments are relative to here, so the block is the same from any folder.
    absWorkingDir: root,
  });
  const code = out.outputFiles[0]!.text.trim();
  return [
    BEGIN,
    code,
    " TCS.g2v = (word) => VISEMES.wordUnits(word).map((u) => u.viseme);",
    END,
  ].join("\n");
};

/** speech.js with its generated block replaced by `block`. */
export const withBlock = (speech: string, block: string): string => {
  const from = speech.indexOf(BEGIN);
  const to = speech.indexOf(END);
  if (from < 0 || to < from) throw new Error("speech.js has no generated visemes block");
  return speech.slice(0, from) + block + speech.slice(to + END.length);
};

if (process.argv[1] === NodeURL.fileURLToPath(import.meta.url)) {
  const speech = NodeFS.readFileSync(SPEECH_JS, "utf8");
  NodeFS.writeFileSync(SPEECH_JS, withBlock(speech, await visemesBlock()));
}
